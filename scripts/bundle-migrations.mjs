/**
 * Flattens the migration folder into one SQL file you can paste into a
 * database console.
 *
 * ## Why this exists
 *
 * `npm run db:migrate` is the right way to apply the schema, and it needs a
 * machine with the repository, Node, and a route to the database. Somebody
 * setting up from a browser — Supabase's SQL editor, a hosted console — has
 * none of those, and pasting 38 files in order by hand is a way to apply 37 of
 * them.
 *
 * ## The part that is easy to get wrong
 *
 * Applying the SQL is only half of it. Drizzle records what it has applied in
 * `drizzle.__drizzle_migrations`, and decides what is pending by comparing
 * each journal entry's `when` against the newest `created_at` in that table. A
 * bundle that created the schema and left that table empty would look, to the
 * next `npm run db:migrate`, like a database with no migrations at all — and
 * it would try to create every table again.
 *
 * So the bookkeeping rows are written too, with the same hash the migrator
 * would have written: SHA-256 of the raw file including its
 * `--> statement-breakpoint` markers, verified against a database the real
 * migrator had already migrated.
 *
 * Usage:
 *   node scripts/bundle-migrations.mjs [output-path]
 *
 * Default output is drizzle/bundle.sql, which is gitignored.
 */
import crypto from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'

const FOLDER = 'drizzle'
const output = process.argv[2] ?? path.join(FOLDER, 'bundle.sql')

const journal = JSON.parse(fs.readFileSync(path.join(FOLDER, 'meta/_journal.json'), 'utf8'))

const parts = []

parts.push(`--
-- AcountrixPlus — complete schema, ${journal.entries.length} migrations flattened into one file.
--
-- Generated by scripts/bundle-migrations.mjs. Do not edit by hand: it is
-- derived from drizzle/*.sql, and a change here would make this file disagree
-- with what the migrator applies everywhere else.
--
-- Paste the whole thing into a SQL console and run it once. It is wrapped in a
-- single transaction, so a failure anywhere leaves the database untouched
-- rather than half built.
--

BEGIN;

-- Refuse a database that already has the schema, rather than failing halfway
-- through with a confusing "relation already exists".
DO $bundle$
BEGIN
  IF to_regclass('public.journal_lines') IS NOT NULL THEN
    RAISE EXCEPTION 'This database already has the AcountrixPlus schema. Nothing applied.';
  END IF;
END
$bundle$;

-- Drizzle's own bookkeeping, created exactly as the migrator creates it.
CREATE SCHEMA IF NOT EXISTS "drizzle";
CREATE TABLE IF NOT EXISTS "drizzle"."__drizzle_migrations" (
  id SERIAL PRIMARY KEY,
  hash text NOT NULL,
  created_at bigint
);
`)

for (const entry of journal.entries) {
  const file = path.join(FOLDER, `${entry.tag}.sql`)
  const query = fs.readFileSync(file, 'utf8')

  // Hashed before the breakpoint markers are stripped. The migrator hashes the
  // raw file, so stripping first would produce a hash that never matches and
  // silently re-apply this migration later.
  const hash = crypto.createHash('sha256').update(query).digest('hex')

  parts.push(`
-- ────────────────────────────────────────────────────────────────────────
-- ${entry.tag}
-- ────────────────────────────────────────────────────────────────────────

${query.split('--> statement-breakpoint').join('').trim()}

INSERT INTO "drizzle"."__drizzle_migrations" (hash, created_at)
VALUES ('${hash}', ${entry.when});
`)
}

// Row Level Security, for the sake of a door this application never uses.
//
// Supabase publishes a PostgREST API over the `public` schema and grants the
// `anon` and `authenticated` roles access to tables created there. This
// application never touches that API — it connects as the table owner over a
// normal Postgres connection and enforces tenant isolation in
// `modules/tenancy` — but the door exists whether or not we walk through it,
// and behind it is every company's ledger.
//
// Enabling RLS with no policies denies those roles everything. It does not
// affect the application: the owner bypasses RLS unless FORCE ROW LEVEL
// SECURITY is set, which it deliberately is not.
//
// Generated as a loop rather than 166 literal statements so a table added by a
// future migration cannot be forgotten here.
parts.push(`
-- ────────────────────────────────────────────────────────────────────────
-- Row Level Security
-- ────────────────────────────────────────────────────────────────────────
--
-- Closes Supabase's anon/authenticated API against every table. This
-- application does not use that API and connects as the table owner, which
-- bypasses RLS — so this changes nothing for it, and everything for anyone
-- holding the project's public anon key.

DO $rls$
DECLARE
  target record;
BEGIN
  FOR target IN
    SELECT tablename FROM pg_tables WHERE schemaname = 'public'
  LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', target.tablename);
  END LOOP;
END
$rls$;

COMMIT;
`)

const sql = parts.join('\n')
fs.writeFileSync(output, sql)

const kb = Math.round(sql.length / 1024)
console.log(`Wrote ${output} — ${journal.entries.length} migrations, ${kb} KB.`)
console.log('Run it once against an empty database. It applies the schema and')
console.log("records it as applied, so a later `npm run db:migrate` sees nothing pending.")
